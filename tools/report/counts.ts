/**
 * Keeps the README's test count honest.
 *
 * Three documents in this repo quote three different numbers, because each was typed by hand at a different moment. A
 * hand-typed count is a claim with no owner; this one is derived from the runner's own JSON report and `--check` fails
 * the build when the README and the suite disagree.
 *
 * Pure: it formats and compares text. All filesystem access belongs to the CLI in test-count.ts.
 */

export const START_MARKER = "<!-- tests:start -->";
export const END_MARKER = "<!-- tests:end -->";

export interface TestCounts {
  readonly files: number;
  readonly tests: number;
  readonly passed: number;
  readonly failed: number;
}

/** Vitest's JSON reporter shape, narrowed to the fields this script trusts. */
interface VitestReport {
  readonly testResults?: readonly unknown[];
  readonly numTotalTestSuites?: number;
  readonly numTotalTests?: number;
  readonly numPassedTests?: number;
  readonly numFailedTests?: number;
}

export function countsFromReport(report: VitestReport): TestCounts {
  // numTotalTestSuites counts describe blocks; the file count is one entry per test file.
  const files = report.testResults?.length ?? report.numTotalTestSuites ?? 0;
  const tests = report.numTotalTests ?? 0;
  if (tests === 0) throw new Error("test report contains no tests: refusing to write a zero count");
  return {
    files,
    tests,
    passed: report.numPassedTests ?? 0,
    failed: report.numFailedTests ?? 0,
  };
}

export function renderBlock(counts: TestCounts): string {
  const plural = counts.tests === 1 ? "test" : "tests";
  const filePlural = counts.files === 1 ? "file" : "files";
  return [
    START_MARKER,
    `**${counts.tests} ${plural} passing** across ${counts.files} ${filePlural}.`,
    "",
    "Generated by `npm run tests:count` from the runner's own report. `npm run verify` fails if this block and the",
    "suite disagree, so the number cannot drift from reality again.",
    END_MARKER,
  ].join("\n");
}

export function replaceBlock(readme: string, block: string): string {
  const start = readme.indexOf(START_MARKER);
  const end = readme.indexOf(END_MARKER);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`README is missing the ${START_MARKER} / ${END_MARKER} markers`);
  }
  return readme.slice(0, start) + block + readme.slice(end + END_MARKER.length);
}
